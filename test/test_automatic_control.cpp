#include "firmware/automatic_control.h"
#include "firmware/startup_actuators.h"

extern "C" { int _fltused = 0; }

#define assert(condition) do { if (!(condition)) return __LINE__; } while (false)

int main() {
  // Retuning strengthens P while preserving both integral rates.
  assert(AutomaticLimits::CO2_KP == 0.04f);
  assert(AutomaticLimits::CO2_TI_SECONDS == 600);
  assert(AutomaticLimits::HUMIDITY_KP == 1.5f);
  assert(AutomaticLimits::HUMIDITY_TI_SECONDS == 900);
  assert(AutomaticLimits::CO2_KP / AutomaticLimits::CO2_TI_SECONDS == 0.02f / 300);
  assert(AutomaticLimits::HUMIDITY_KP / AutomaticLimits::HUMIDITY_TI_SECONDS == 1.0f / 600);
  PiController pi(2, 10);
  assert(pi.update(20, 10, 0, 20) == 20);
  assert(pi.terms().i == 0);  // No accumulation against the upper limit.
  assert(pi.update(5, 1, 0, 20) == 11);
  assert(pi.update(-20, 10, 0, 20) == 0);
  assert(pi.terms().i == 0);  // Unwind to zero without negative integral debt.
  assert(pi.terms().p == -40 && pi.terms().sum == 0);

  ControlSettings settings;
  settings.co2Ppm = 2500;
  ControlInput input;
  input.hardwareReady = true;
  input.co2Valid = true;
  input.humidityValid = true;
  input.co2 = 600;
  input.humidity = 91;
  input.co2At = input.humidityAt = 1000;
  input.rpmValid = true;
  input.rpm = 650;
  AutomaticControl control;
  assert(!control.enabled() && !control.ownsOutputs());
  control.setEnabled(true, 1000);
  control.poll(1000, input, settings, true, false);
  assert(control.enabled() && control.fanPercent() == 0 && !control.foggerOn(1000));

  input.co2 = 2540;
  input.co2At = 2000;
  control.poll(2000, input, settings, true, false);
  assert(control.fanPercent() == 2);
  input.co2 = 2600;
  input.co2At = 3000;
  control.poll(3000, input, settings, true, false);
  assert(control.fanPercent() == 4 && control.foggerPercent() == 0);
  const float integral = control.co2Terms().i;
  control.poll(4000, input, settings, true, false);
  assert(control.co2Terms().i == integral);  // Integrate a sensor sample only once.
  input.co2At = 8000;
  control.poll(8000, input, settings, true, false);
  assert(control.co2Terms().i > integral);
  input.co2 = 10000;
  input.co2At = 13000;
  control.poll(13000, input, settings, true, false);
  assert(control.fanPercent() == 80 && !control.foggerOn(13000));

  // Startup pulses run before the automatic controller takes ownership.
  StartupActuators hardware;
  hardware.begin(0);
  hardware.poll(1000, false);
  assert(pinValues[3] == HIGH && hardware.status().foggerOn && pwmDuty == 255);
  hardware.poll(13000, false, true, &control);
  assert(pwmDuty == 80*255/100 && pinValues[3] == LOW);

  input.co2 = 2400;
  input.co2At = 18000;
  control.poll(18000, input, settings, true, false);
  assert(control.fanPercent() == 0 && control.co2Terms().p < 0);
  input.co2 = 3000;
  input.co2At = 19000;
  control.poll(19000, input, settings, true, false);
  control.poll(19001, input, settings, false, false);
  assert(!control.enabled() && control.fanPercent() == 0);
  control.poll(19002, input, settings, true, false);
  assert(!control.enabled());

  control.setEnabled(true, 20000);
  input.co2At = 20000;
  control.poll(20000, input, settings, true, false);
  input.co2At = 25000;
  input.rpm = 0;
  control.poll(25000, input, settings, true, false);
  assert(control.fault() && control.fanPercent() == 10 && !control.foggerOn(25000));
  input.rpm = 1000;
  control.poll(25001, input, settings, true, false);
  assert(control.fault());  // No silent fault restart.
  control.setEnabled(true, 30000);
  input.co2At = 10000;
  control.poll(30000, input, settings, true, false);
  assert(control.fault());

  control.setEnabled(true, 40000);
  input.co2At = 40000;
  input.scdHumidityValid = true;
  input.scdHumidity = 96;
  control.poll(40000, input, settings, true, false);
  assert(!control.fault() && control.fanPercent() > 0);
  input.scdHumidity = 100;
  control.poll(40000, input, settings, true, false);
  assert(!control.fault());
  input.scdHumidity = 80;
  control.setEnabled(true, 40001);
  control.poll(40001, input, settings, true, true);
  assert(!control.enabled() && control.fanPercent() == 0);

  control.setEnabled(true, 0xFFFFFF00U);
  input.co2At = 0xFFFFFF00U;
  control.poll(0xFFFFFF00U, input, settings, true, false);
  input.co2At += 5000;
  control.poll(input.co2At, input, settings, true, false);
  assert(!control.fault() && control.enabled());
  control.releaseToManual();
  assert(!control.enabled() && !control.ownsOutputs());

  control.setEnabled(true, 100000);
  input.co2 = 3000;
  input.co2At = 100000;
  input.co2Valid = true;
  control.poll(100000, input, settings, true, false);
  const uint8_t heldFan = control.fanPercent();
  const float heldIntegral = control.co2Terms().i;
  input.co2Valid = false;
  input.co2At = 105000;
  control.poll(105000, input, settings, true, false);
  assert(!control.fault() && control.fanPercent() == heldFan);
  assert(control.co2Terms().i == heldIntegral);
  input.co2At = 110000;
  input.co2Valid = true;
  control.poll(110000, input, settings, true, false);
  assert(!control.fault());
  input.co2Valid = false;
  control.poll(124999, input, settings, true, false);
  assert(!control.fault());
  control.poll(125000, input, settings, true, false);
  assert(control.fault() && control.fanPercent() == 10);
  input.co2Valid = true;
  input.co2At = 125001;
  control.poll(125001, input, settings, true, false);
  assert(control.fault());

  AutomaticControl humidity;
  input.co2 = 3000;
  input.co2Valid = input.humidityValid = input.rpmValid = true;
  input.co2At = input.humidityAt = 200000;
  input.humidity = 85;
  input.rpm = 650;
  humidity.setEnabled(true, 200000);
  humidity.poll(200000, input, settings, true, false);
  assert(humidity.foggerPercent() == 8 && humidity.humidityTerms().i == 0);
  assert(humidity.foggerPeriodMs() == 1250);
  assert(humidity.foggerOn(200000) && humidity.foggerOn(200099));
  assert(!humidity.foggerOn(200100) && !humidity.foggerOn(201249));
  assert(humidity.foggerOn(201250));
  hardware.poll(200000, false, true, &humidity);
  assert(pinValues[3] == HIGH);
  hardware.poll(200100, false, true, &humidity);
  assert(pinValues[3] == LOW);
  input.co2At = 205000;
  humidity.poll(205000, input, settings, true, false);
  assert(humidity.humidityTerms().i == 0);  // Held RH must not accumulate I.
  input.co2At = input.humidityAt = 265000;
  humidity.poll(265000, input, settings, true, false);
  assert(humidity.humidityTerms().i > 0.54f && humidity.humidityTerms().i < 0.55f);
  assert(humidity.foggerPercent() == 8);
  input.co2 = 1000;
  input.co2At = 270000;
  humidity.poll(270000, input, settings, true, false);
  assert(humidity.fanPercent() == 0 && humidity.foggerPercent() > 0);
  assert(humidity.humidityTerms().i > 0);  // Rotation still permits fogging at zero PWM.
  input.rpm = 0;
  humidity.poll(270001, input, settings, true, false);
  assert(humidity.foggerPercent() == 0 && humidity.humidityTerms().i > 0);
  input.co2 = 3000;
  input.co2At = 275000;
  input.rpm = 0;
  humidity.poll(275000, input, settings, true, false);
  assert(humidity.foggerPercent() == 0 && !humidity.fault());
  input.rpm = 650;
  input.humidityValid = false;
  input.co2At = 276000;
  humidity.poll(276000, input, settings, true, false);
  assert(humidity.foggerPercent() == 0);
  input.humidityValid = true;
  input.humidity = 90.6f;
  input.co2At = input.humidityAt = 277000;
  humidity.poll(277000, input, settings, true, false);
  assert(humidity.foggerPercent() == 0 && humidity.humidityTerms().p < 0);
  input.humidity = 95;
  input.co2At = input.humidityAt = 278000;
  humidity.poll(278000, input, settings, true, false);
  assert(humidity.foggerPercent() == 0);
  input.humidity = 40;
  input.co2At = input.humidityAt = 280000;
  humidity.poll(280000, input, settings, true, false);
  assert(humidity.foggerPercent() == 50 && humidity.humidityTerms().i == 0);
  input.co2At = 415000;
  humidity.poll(415000, input, settings, true, false);
  assert(humidity.foggerPercent() == 0 && !humidity.fault());
  humidity.poll(415001, input, settings, false, false);
  assert(!humidity.enabled() && !humidity.foggerOn(415001));
  // Retain accumulated demand at the setpoint and unwind below it.
  AutomaticControl smooth;
  input.co2 = 3000;
  input.humidity = 85;
  input.co2At = input.humidityAt = 500000;
  smooth.setEnabled(true, 500000);
  smooth.poll(500000, input, settings, true, false);
  input.co2At = input.humidityAt = 800000;
  smooth.poll(800000, input, settings, true, false);
  assert(smooth.co2Terms().i == 10);
  smooth.resetIntegrals();
  assert(smooth.enabled() && !smooth.fault() && smooth.resetCount() == 1);
  assert(smooth.co2Terms().i == 0 && smooth.humidityTerms().i == 0);
  assert(smooth.co2Terms().p == 20 && smooth.co2Terms().sum == 20);
  input.co2At = 800001;
  smooth.poll(800001, input, settings, true, false);
  input.co2At = 1100001;
  input.humidityAt = 1100001;
  smooth.poll(1100001, input, settings, true, false);
  assert(smooth.co2Terms().i == 10);
  // Reset timing for the remaining independent rundown scenario.
  smooth.setEnabled(true, 500000);
  input.co2At = input.humidityAt = 500000;
  smooth.poll(500000, input, settings, true, false);
  input.co2At = input.humidityAt = 800000;
  smooth.poll(800000, input, settings, true, false);
  input.co2 = 2500;
  input.co2At = 805000;
  smooth.poll(805000, input, settings, true, false);
  assert(smooth.co2Terms().sum == 10 && smooth.fanPercent() == 10);
  assert(smooth.foggerPercent() > 0);
  input.co2 = 2400;
  input.co2At = 810000;
  smooth.poll(810000, input, settings, true, false);
  assert(smooth.co2Terms().i < 10 && smooth.co2Terms().i > 9);
  assert(smooth.fanPercent() == 6 && smooth.foggerPercent() > 0);
  input.co2 = 1900;
  input.co2At = 815000;
  smooth.poll(815000, input, settings, true, false);
  assert(smooth.co2Terms().sum == 0 && smooth.fanPercent() == 0);
  assert(smooth.foggerPercent() > 0 && !smooth.fault());
  input.rpm = 30;
  smooth.poll(815001, input, settings, true, false);
  assert(smooth.foggerPercent() > 0);  // No minimum RPM threshold.
  input.rpm = 0;
  smooth.poll(815002, input, settings, true, false);
  assert(smooth.foggerPercent() == 0);
  input.rpm = 650;
  input.co2 = 2540;
  input.co2At = 820000;
  smooth.poll(820000, input, settings, true, false);
  assert(smooth.co2Terms().i > 0);
  input.co2 = 2560;
  input.co2At = 825000;
  smooth.poll(825000, input, settings, true, false);
  assert(smooth.fanPercent() > 0);
  input.co2At = 831000;
  smooth.poll(831000, input, settings, true, false);
  assert(!smooth.fault() && smooth.fanPercent() > 0);
  input.rpmValid = false;
  smooth.poll(831001, input, settings, true, false);
  assert(smooth.foggerPercent() == 0);
  AutomaticControl idle;
  input.co2Valid = false;
  idle.resumeIfIdle(831001, input, false, true, false);
  assert(!idle.enabled());
  input.co2Valid = true;
  idle.resumeIfIdle(831001, input, true, true, false);
  assert(!idle.enabled());
  idle.resumeIfIdle(831001, input, false, false, false);
  assert(!idle.enabled());
  idle.resumeIfIdle(831001, input, false, true, true);
  assert(!idle.enabled());
  idle.resumeIfIdle(831001, input, false, true, false);
  assert(idle.enabled());
  idle.poll(831001, input, settings, false, false);
  assert(!idle.enabled());
  idle.resumeIfIdle(831002, input, false, true, false);
  assert(idle.enabled());
  input.co2Valid = false;
  idle.poll(900000, input, settings, true, false);
  assert(idle.fault());
  idle.resetIntegrals();
  idle.resumeIfIdle(900000, input, false, true, false);
  assert(idle.fault());  // Reset and automatic default must not clear faults.
  AutomaticControl pause;
  input.co2 = 2000;
  input.co2Valid = input.humidityValid = input.rpmValid = true;
  input.humidity = 85;
  input.rpm = 650;
  input.co2At = input.humidityAt = 2000000;
  pause.setEnabled(true, 2000000);
  pause.poll(2000000, input, settings, true, false);
  input.co2At = input.humidityAt = 2065000;
  pause.poll(2065000, input, settings, true, false);
  const float pausedIntegral = pause.humidityTerms().i;
  assert(pausedIntegral > 0 && pause.foggerPercent() == 8);
  input.rpm = 0;
  pause.poll(2065001, input, settings, true, false);
  assert(pause.foggerPercent() == 0 && !pause.foggerOn(2065001));
  input.humidity = 84;
  input.co2At = input.humidityAt = 2125000;
  pause.poll(2125000, input, settings, true, false);
  assert(pause.humidityTerms().i == pausedIntegral);
  input.rpm = 650;
  input.co2At = 2155000;
  pause.poll(2155000, input, settings, true, false);
  assert(pause.humidityTerms().i == pausedIntegral);
  assert(pause.humidityTerms().p == 9 && pause.foggerPercent() == 10);
  input.co2At = input.humidityAt = 2190000;
  pause.poll(2190000, input, settings, true, false);
  assert(pause.humidityTerms().i > 0.89f && pause.humidityTerms().i < 0.90f);
  input.rpm = 0;
  input.humidity = 91;
  input.co2At = input.humidityAt = 2195000;
  pause.poll(2195000, input, settings, true, false);
  assert(pause.humidityTerms().i > 0 && pause.foggerPercent() == 0);
  // Normal RH overshoot must unwind I without clearing learned demand.
  AutomaticControl continuous;
  settings.co2Ppm = 1500;
  settings.humidityRh = 98;
  input.co2 = 1600;
  input.humidity = 96;
  input.rpm = 3000;
  input.rpmValid = input.humidityValid = input.co2Valid = true;
  input.co2At = input.humidityAt = 3000000;
  continuous.setEnabled(true, 3000000);
  continuous.poll(3000000, input, settings, true, false);
  input.co2At = input.humidityAt = 3600000;
  continuous.poll(3600000, input, settings, true, false);
  assert(continuous.humidityTerms().i == 2);
  input.humidity = 98.62f;
  input.co2At = input.humidityAt = 3605000;
  continuous.poll(3605000, input, settings, true, false);
  assert(continuous.humidityTerms().p < 0 && continuous.humidityTerms().i > 1.9f);
  assert(continuous.foggerPercent() > 0 && !continuous.fault());
  input.humidity = 100;
  input.co2 = 1000;
  input.co2At = input.humidityAt = 4205000;
  continuous.poll(4205000, input, settings, true, false);
  assert(continuous.humidityTerms().i == 0 && continuous.foggerPercent() == 0);
  assert(continuous.co2Terms().p < 0 && continuous.co2Terms().i == 0);
  assert(continuous.fanPercent() == 0 && !continuous.fault());
  // Large negative error cannot accumulate negative integral debt.
  assert(pi.update(-100, 100000, 0, 20) == 0 && pi.terms().i == 0);
  CyclicMist timer;
  assert(!timer.configure({true, 0, 10}, 0));
  assert(!timer.configure({true, 11, 10}, 0));
  assert(timer.configure({true, 1, 59}, 0));
  timer.poll(60000);
  assert(!timer.misting() && timer.remainingMs(60000) == 3540000);
  timer.poll(3600000);
  assert(timer.misting());
  assert(timer.configure({true, 1, 10}, 0xFFFFFF00U));
  timer.poll(0xFFFFFF00U + 60000U);
  assert(!timer.misting() && timer.remainingMs(0xFFFFFF00U + 60000U) == 600000);
  timer.poll(0xFFFFFF00U + 660000U);
  assert(timer.misting());
  timer.poll(0xFFFFFF00U + 660000U * 5 + 500U);
  assert(timer.misting() && timer.remainingMs(0xFFFFFF00U + 660000U * 5 + 500U) == 59500);

  AutomaticControl mist;
  input.co2 = 1700;
  input.humidity = 95;
  input.rpm = 3000;
  input.rpmValid = input.humidityValid = input.co2Valid = true;
  input.co2At = input.humidityAt = 5000000;
  mist.setEnabled(true, 5000000);
  mist.poll(5000000, input, settings, true, false);
  input.co2At = input.humidityAt = 5065000;
  mist.poll(5065000, input, settings, true, false);
  const float mistIntegral = mist.humidityTerms().i;
  const float fanIntegral = mist.co2Terms().i;
  const float fanP = mist.co2Terms().p;
  assert(mistIntegral > 0);
  assert(mist.configureCyclicMist({true, 2, 58}, 5065000));
  assert(mist.humidityTerms().i == mistIntegral && mist.co2Terms().i == fanIntegral);
  assert(mist.configureCyclicMist({true, 1, 10}, 5065000));
  assert(mist.humidityTerms().i == mistIntegral && mist.co2Terms().i == fanIntegral);
  mist.poll(5065000, input, settings, false, false);
  assert(mist.enabled() && mist.foggerPercent() == 100 && mist.foggerOn(5065000));
  assert(mist.humidityTerms().i == mistIntegral);
  input.co2At = input.humidityAt = 5124999;
  input.humidity = 97;
  input.co2 = 1900;
  mist.poll(5124999, input, settings, false, false);
  assert(mist.foggerPercent() == 100 && mist.humidityTerms().i == mistIntegral);
  assert(mist.co2Terms().i == fanIntegral && mist.co2Terms().p == fanP);
  assert(mist.fanPercent() == 50);
  input.humidityAt = 5125000;
  input.co2At = 5124999;
  mist.poll(5125000, input, settings, false, false);
  assert(!mist.cyclicMist().misting() && mist.foggerPercent() < 50);
  assert(mist.co2Terms().i == fanIntegral && mist.co2Terms().p == 16);
  assert(mist.fanPercent() == 17);
  assert(mist.humidityTerms().i == mistIntegral && mist.humidityTerms().p == 1.5f);
  input.co2At = input.humidityAt = 5190000;
  mist.poll(5190000, input, settings, false, false);
  assert(mist.humidityTerms().i > mistIntegral && mist.humidityTerms().i < mistIntegral + 0.11f);
  assert(mist.co2Terms().i > 2.59f && mist.co2Terms().i < 2.61f);
  input.co2At = input.humidityAt = 5725000;
  mist.poll(5725000, input, settings, false, false);
  assert(mist.cyclicMist().misting() && mist.foggerPercent() == 100);
  const float afterPauseIntegral = mist.humidityTerms().i;
  assert(mist.configureCyclicMist({false, 0, 10}, 5725001));
  mist.poll(5725001, input, settings, true, false);
  assert(mist.foggerPercent() < 50 && mist.humidityTerms().i == afterPauseIntegral);
  mist.restoreCyclicMist({true, 1, 10}, 5725002);
  mist.releaseToManual();
  assert(!mist.enabled() && mist.cyclicMist().settings().enabled);
  mist.resumeIfIdle(5725002, input, false, false, false);
  assert(mist.enabled());
  mist.poll(5725002, input, settings, false, false);
  assert(mist.foggerPercent() == 100);
  mist.poll(5725003, input, settings, false, true);
  assert(!mist.enabled() && !mist.foggerOn(5725003) && mist.cyclicMist().settings().enabled);
  HumidityEmergency guard;
  const uint32_t origin = 0xFFFF0000U;
  for (uint32_t elapsed = 0; elapsed <= HumidityEmergency::DELAY_MS; elapsed += 1000) {
    guard.poll(origin + elapsed, true, 135000);
  }
  assert(!guard.active());
  guard.poll(origin + HumidityEmergency::DELAY_MS + 1, true, 135000);
  assert(guard.active());
  guard.poll(origin + HumidityEmergency::DELAY_MS + 2, false, 135000);
  guard.clearPending();
  assert(guard.active());
  guard.release();
  assert(!guard.active());
  guard.poll(0, true, 135000);
  guard.poll(1800001, true, 135000);
  assert(!guard.active()); // An unobserved interval is not a continuous deficit.
  guard.poll(1800002, false, 135000);
  guard.poll(1800003, true, 135000);
  assert(!guard.active());

  AutomaticControl dry;
  input.hardwareReady = input.co2Valid = input.humidityValid = input.rpmValid = true;
  input.rpm = 3000;
  input.co2 = 1800;
  input.humidity = settings.humidityRh - 11;
  dry.setEnabled(true, 0);
  assert(dry.configureCyclicMist({true, 5, 55}, 0));
  for (uint32_t now = 0; now <= 1801000; now += 1000) {
    input.co2At = input.humidityAt = now;
    dry.poll(now, input, settings, true, false);
  }
  assert(dry.humidityEmergency() && dry.effectiveCo2Target(1500) == 5000);
  assert(dry.fanPercent() == 0 && !dry.cyclicMisting());
  input.co2At = input.humidityAt = 3600000;
  input.humidity = settings.humidityRh;
  dry.poll(3600000, input, settings, true, false);
  assert(dry.cyclicMist().misting() && !dry.cyclicMisting() && dry.fanPercent() == 0);
  dry.resetIntegrals();
  assert(dry.humidityEmergency());
  dry.setEnabled(false, 3600001);
  dry.setEnabled(true, 3600002);
  assert(dry.humidityEmergency());
  dry.releaseToManual();
  assert(!dry.humidityEmergency());
  dry.setEnabled(true, 3600003);
  assert(dry.effectiveCo2Target(1500) == 1500);
  assert(AutomaticLimits::STARTUP_TEST_ENABLED);
  return 0;
}
